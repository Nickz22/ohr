# 2. brew install pip3
# 3. Create and add a GITHUB_TOKEN environment variable to `.zshrc` (https://github.com/settings/apps)
# 4. Execute python3 ./scripts/python/github/read_and_deploy_pr_files_changed.py
# 5. Provide the github url whose files you want to deploy
